# Создаём пустой словарь для хранения контактов
# Формат: {"Имя": "номер телефона"}
contacts = {}

# Бесконечный цикл — программа работает, пока пользователь не выберет выход
while True:
    # Выводим меню с вариантами действий
    print("\n--- Телефонная книга ---")
    print("1 - Добавить контакт")
    print("2 - Удалить контакт")
    print("3 - Вывести все контакты")
    print("4 - Выход")

    # Просим пользователя ввести номер действия
    # input() сам по себе всегда возвращает строку, поэтому сравнивать будем со строками "1", "2" и т.д.
    choice = input("Выберите действие: ")

    # Если пользователь выбрал "1" — добавляем контакт
    if choice == "1":
        # Запрашиваем имя контакта (это будет ключ словаря)
        name = input("Введите имя контакта: ")

        # Запрашиваем номер телефона (это будет значение)
        phone = input("Введите номер телефона (только цифры): ")

        # Проверяем, что номер состоит только из цифр
        # .isdigit() возвращает True, если строка состоит только из цифр
        if phone.isdigit():
            # Сохраняем контакт в словарь
            # contacts[name] = phone — записываем по ключу name значение phone
            contacts[name] = phone
            print(f"Контакт '{name}' добавлен.")
        else:
            # Если в номере есть буквы или символы — сообщаем об ошибке
            print("Ошибка: номер должен содержать только цифры!")

    # Если пользователь выбрал "2" — удаляем контакт
    elif choice == "2":
        # Запрашиваем имя контакта, который нужно удалить
        name = input("Введите имя контакта для удаления: ")

        # Проверяем, существует ли такой ключ в словаре
        # Оператор in проверяет наличие ключа в словаре
        if name in contacts:
            # del удаляет пару ключ-значение из словаря
            del contacts[name]
            print(f"Контакт '{name}' удалён.")
        else:
            # Если такого контакта нет — сообщаем пользователю
            print(f"Контакт '{name}' не найден.")

    # Если пользователь выбрал "3" — выводим все контакты
    elif choice == "3":
        # Проверяем, пуст ли словарь
        # Если словарь пуст — len(contacts) вернёт 0, а not 0 = True
        if not contacts:
            print("Телефонная книга пуста.")
        else:
            print("\n--- Список контактов ---")
            # .items() возвращает пары (ключ, значение) для перебора
            # name — имя контакта, phone — номер
            for name, phone in contacts.items():
                print(f"{name}: {phone}")

    # Если пользователь выбрал "4" — выходим из программы
    elif choice == "4":
        print("Выход из программы. До свидания!")
        # break прерывает цикл while — программа завершается
        break

    # Если пользователь ввёл что-то другое (не 1, 2, 3, 4)
    else:
        print("Неверный выбор. Попробуйте снова.")