# Функция проверки: угадали ли мы число
def is_correct(guess, secret):
    # Если наше предположение равно загаданному числу — возвращаем True
    if guess == secret:
        return True
    # Иначе возвращаем False
    return False


# Основная функция бинарного поиска
def guess_number(secret):
    # Устанавливаем нижнюю границу диапазона (минимум -10^9)
    low = -10 ** 9
    # Устанавливаем верхнюю границу диапазона (максимум 10^9)
    high = 10 ** 9



    # Запускаем цикл, пока нижняя граница не превысит верхнюю
    while low <= high:


        # Находим середину текущего диапазона (целочисленное деление)
        mid = (low + high) // 2

        # Проверяем, является ли середина загаданным числом
        if is_correct(mid, secret):
            # Если да — возвращаем число и количество попыток
            return mid
        # Если наше число меньше загаданного
        elif mid < secret:
            # Сдвигаем нижнюю границу вправо (ищем в большей половине)
            low = mid + 1
        # Если наше число больше загаданного
        else:
            # Сдвигаем верхнюю границу влево (ищем в меньшей половине)
            high = mid - 1

    # Если число не найдено (такое невозможно при верном диапазоне), возвращаем None
    return None


# Точка входа в программу
if __name__ == "__main__":
    # Загадываем число для теста (в реальной задаче оно приходит извне)
    secret_number = int(input())

    # Вызываем функцию угадывания и получаем результат
    result = guess_number(secret_number)

    # Выводим на экран загаданное число и количество затраченных попыток
    print(f"Загаданное число: {result}")
